/** Normaliza para busca: sem acento, sem caixa, sem espaços extras. */
export function normalizar(texto: string): string {
  return texto
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

/**
 * Busca por label, nome técnico, produto ou mesa.
 * "faixa" acha "Faixas de escore"; "FAIXAS" tambem.
 */
export function buscarNoIndice(termo: string): RegistroDoBanco[] {
  const alvo = normalizar(termo);
  if (!alvo) return indiceDoBanco;
  return indiceDoBanco.filter((registro) =>
    normalizar(registro.label).includes(alvo) ||
    normalizar(registro.name).includes(alvo) ||
    normalizar(registro.produto).includes(alvo) ||
    (registro.admin ? normalizar(registro.admin.mesa).includes(alvo) : false),
  );
}

/** As tabelas que a área admin abre em mesa própria. */
export function tabelasDaAdmin(): RegistroDoBanco[] {
  return indiceDoBanco.filter((registro) => registro.admin !== null);
}

/** A label de uma tabela pelo nome técnico. */
export function labelDaTabela(nome: string): string | null {
  return indiceDoBanco.find((registro) => registro.name === nome)?.label ?? null;
}
