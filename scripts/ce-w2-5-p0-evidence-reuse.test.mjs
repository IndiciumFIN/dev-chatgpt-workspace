import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {normalizeReviewEvidence,projectEvidenceReuse,sameCanonicalBaseline} from "./ce-w2-5-p0-evidence-reuse.mjs";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const first=read("registers/governance/ce-w2-5-p0-firstwave-review-20261121.v1.json");
const second=read("registers/governance/ce-w2-5-p0-secondwave-review-20261121.v1.json");
const third=read("registers/governance/ce-w2-5-p0-thirdwave-review-20261121.v1.json");
test("W2.5 automatically projects sixteen static P0 reviews onto all six Git-pinned manifests",()=>{
 const report=projectEvidenceReuse();
 assert.equal(report.protocol,"CE.CROSS.W2.5.P0.EVIDENCE_REUSE.v1");
 assert.equal(report.state,"PRELIMINARY_STATIC_ONLY_NO_ADMISSION");
 assert.equal(report.source_manifest_batches,6);
 assert.equal(report.source_commits,22);
 assert.equal(report.source_branches,23);
 assert.equal(report.total_p0_occurrences,842);
 assert.equal(report.total_p0_unique_objects,359);
 assert.equal(report.reviewed_p0_unique_objects,16);
 assert.equal(report.unique_p0_preliminary_progress_percent,4.46);
 assert.equal(report.remaining_p0_unique_objects,343);
 assert.equal(report.direct_review_registrations,37);
 assert.ok(report.reviewed_p0_occurrences>=37);
 assert.ok(report.same_content_different_baseline_hold_occurrences>=1);
 assert.equal(report.reviewed_p0_occurrences+report.same_content_different_baseline_hold_occurrences<=842,true);
 assert.ok(report.sources_with_exact_content_matches>=3);
 assert.ok(report.branches_with_exact_content_matches>=3);
 assert.equal(report.independent_approvals,0);
 assert.equal(report.final_semantic_dispositions,0);
 assert.equal(report.branch_closures,0);
 assert.equal(report.remote_db_writes,0);
 assert.equal(report.source_writes,0);
 assert.equal(report.merge_authorized,false);
});
test("reuse rejects spoofed SHA, forged approval and conflicting prior decision",()=>{
 const docs=[first,second,third];
 const validated=normalizeReviewEvidence(docs);
 assert.equal(validated.canonical.size,16);
 assert.equal(validated.registrations.size,37);
 const fake=structuredClone(docs);
 fake[0].independent_review_complete=true;
 assert.throws(()=>normalizeReviewEvidence(fake),/claims closure/);
 const drift=structuredClone(docs);
 drift[2].records[0].source_blob_sha="x";
 assert.throws(()=>normalizeReviewEvidence(drift),/invalid source evidence/);
 const contradiction=structuredClone(docs);
 const match=contradiction[1].records.find(x=>x.exact_reuse_from_first_wave);
 assert.ok(match);
 match.provisional_decision="INTEGRATE_WITHOUT_APPROVAL";
 assert.throws(()=>normalizeReviewEvidence(contradiction),/contradictory P0 finding/);
});

test("same content but different canonical baseline is quarantined, never auto-cleared",()=>{
 assert.equal(sameCanonicalBaseline("a","a"),true);
 assert.equal(sameCanonicalBaseline(null,undefined),true);
 assert.equal(sameCanonicalBaseline("a","b"),false);
 assert.equal(sameCanonicalBaseline(null,"a"),false);
});
