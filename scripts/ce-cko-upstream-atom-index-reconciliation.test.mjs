import {test} from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
const read=p=>readFileSync(new URL("../"+p,import.meta.url));
const d=JSON.parse(read("registers/governance/ce-cko-upstream-atom-index-reconciliation-20261128.v1.json"));
test("upstream index closes historical identity gaps without materializing or admitting held evidence",()=>{
 const bytes=read(d.predecessor.path);
 assert.equal(createHash("sha1").update("blob "+bytes.length+"\0").update(bytes).digest("hex"),d.predecessor.git_blob_sha);
 const p=JSON.parse(bytes).reconciliation,a=d.reconciliation;
 assert.equal(a.pair_total,p.pair_count);
 assert.equal(a.pairs_matched_upstream_index,a.pair_total);
 assert.equal(a.active_atoms_exact_match,p.atom_count);
 assert.equal(a.active_pairs_original_match,4142);
 assert.equal(a.metadata_only_atoms,a.historical_index_atoms-a.materialized_atoms);
 assert.equal(a.groups.reduce((n,x)=>n+x.index_atoms,0),a.historical_index_atoms);
 assert.equal(a.groups.reduce((n,x)=>n+x.pairs,0),a.pair_total);
 assert.equal(a.groups.reduce((n,x)=>n+x.matched_pairs,0),a.pair_total);
 const held=a.groups.filter(x=>x.gate!=="DEFAULT_ACTIVE");
 assert.equal(held.reduce((n,x)=>n+x.pairs,0),a.previously_missing_pairs);
 assert.equal(held.reduce((n,x)=>n+x.held_distinct_atoms,0),a.matched_previously_missing_distinct_atom_ids);
 assert.equal(held.reduce((n,x)=>n+x.held_distinct_sources,0),a.matched_previously_missing_sources);
 assert.ok(held.every(x=>x.materialized_pairs===0&&x.default_retrieval_atoms===0));
 assert.equal(a.source_mismatches,0);
 assert.equal(a.gate_mismatches,0);
 assert.equal(a.held_pairs_with_default_retrieval_enabled,0);
 assert.equal(a.held_pairs_without_64_character_hash,0);
 assert.equal(a.held_pairs_with_materialized_text_in_upstream_atoms,0);
 assert.ok(Object.values(d.controls).every(x=>x===false));
});
