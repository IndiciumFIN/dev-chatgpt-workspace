import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const load=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
test("W2.5.5 Grook all 47 pinned deltas compared, none prematurely SEALED",()=>{
 const pointer=load("registers/governance/ce-w2-5-review-current-20261120.v1.json"),r=load(pointer.latest_manifest),q=load(r.source_queue),p=load(r.prior_p0_review);
 assert.equal(pointer.latest_manifest,"registers/governance/ce-w2-5-grook-full-blob-comparison-20261120.v1.json");
 assert.equal(r.protocol,"CE.CROSS.W2.5.5.GROOK_BLOB_COMPARISON.v1");
 assert.equal(r.main_review_sha,"d0f0b26c96890e533eef6d35a2a09f52b73c580e");
 assert.equal(r.source_commit_sha,q.source_commit_sha);
 assert.equal(r.source_tree_sha,q.source_tree_sha);
 const expected=q.queue.filter(x=>x.content_review==="PENDING");
 assert.equal(expected.length,32);
 assert.equal(r.items.length,expected.length);
 assert.equal(new Set(r.items.map(x=>x.path)).size,32);
 for(let i=0;i<expected.length;i++){
  const a=r.items[i],b=expected[i];
  assert.equal(a.path,b.path);
  assert.equal(a.origin_blob_sha,b.origin_row[2]);
  assert.equal(a.canonical_blob_sha,b.origin_row[3]);
  assert.equal(a.comparison_status,"BOTH_IMMUTABLE_BLOBS_INSPECTED");
  assert.ok(a.observed_difference.length>20);
  assert.ok(a.required_confirmation.length>10);
  assert.equal(a.final_decision,null);
  assert.equal(a.merge_eligible,false);
  assert.equal(a.independent_review,"PENDING");
 }
 assert.equal(r.counts.prior_p0_compared,p.records.length);
 assert.equal(r.counts.prior_p1_p2_compared,q.counts.non_p0_content_compared);
 assert.equal(r.counts.new_blob_comparisons,32);
 assert.equal(r.counts.all_branch_blob_comparisons,r.counts.prior_p0_compared+r.counts.prior_p1_p2_compared+r.counts.new_blob_comparisons);
 assert.equal(r.counts.all_branch_blob_comparisons,47);
 assert.equal(r.counts.provisional_preserve_main,30);
 assert.equal(r.counts.escalated_risk_holds,2);
 assert.deepEqual(r.items.filter(x=>x.discovered_priority==="P0_CANDIDATE").map(x=>x.path).sort(),["src/components/site/areas.tsx","src/lib/contract-index.generated.ts"].sort());
 assert.equal(r.contract_index_gap.source_ids_absent_in_canonical,149);
 assert.equal(r.contract_index_gap.missing_group_counts["CE-TOOL"],78);
 assert.equal(r.contract_index_gap.missing_group_counts["CE-COMP"],70);
 assert.equal(r.contract_index_gap.missing_group_counts["CE-ROUTE"],1);
 assert.equal(r.counts.final_approved_dispositions,0);
 assert.equal(r.counts.independent_reviews,0);
 assert.equal(r.counts.sealed_branches,0);
 assert.equal(r.semantic_decisions_approved,0);
 assert.equal(r.closure_status,"OPEN");
 assert.equal(r.no_revisit,false);
 assert.equal(r.merge_authorized,false);
 assert.equal(r.delete_authorized,false);
 assert.equal(r.remote_database_write_authorized,false);
 assert.equal(pointer.branch_closure_status,"OPEN");
});
