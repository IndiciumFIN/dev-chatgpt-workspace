import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {loadBranchClosureReadiness,validateBranchClosureReadiness} from "./ce-w2-5-audit-hardening-closure-readiness.mjs";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const path="registers/governance/ce-w2-5-audit-hardening-closure-readiness-20261121.v1.json";
const index=read("registers/governance/ce-w2-4-orphan-full-file-index-20261120.v1.json");
const doc=read(path);
const manifest=read(doc.w2_4_manifest_path);
test("audit-hardening: all 421 differences pinned, 282 exact-content mode-only; none SEALED",()=>{
 const r=loadBranchClosureReadiness();
 assert.equal(r.status,"PASS_STRUCTURAL_ONLY_NO_CLOSURE");
 assert.equal(r.source_files,1733);
 assert.equal(r.exact_files,1312);
 assert.equal(r.delta_files,421);
 assert.equal(r.canonical_only_files,1409);
 assert.equal(r.mode_only,282);
 assert.equal(r.mode_and_bytes,5);
 assert.equal(r.content_only,134);
 assert.deepEqual(r.priority,{P0:11,P1:126,P2:284});
 assert.equal(r.semantic_final,0);
 assert.equal(r.independent_approval,false);
 assert.equal(r.SEALED,false);
});
test("audit-hardening: refuse a forged Leivis self-approval or claimed SEALED/main merge",()=>{
 const c=structuredClone(doc);
 c.closure.owner_approval_recorded=true;
 assert.throws(()=>validateBranchClosureReadiness(c,index,manifest),/false closure/);
 const self=structuredClone(doc);
 self.closure.independent_reviewer="Leivis Lima";
 self.closure.independent_review_recorded=true;
 assert.throws(()=>validateBranchClosureReadiness(self,index,manifest),/false closure/);
 const sealed=structuredClone(doc);
 sealed.closure.SEALED=true;
 sealed.closure.no_revisit=true;
 assert.throws(()=>validateBranchClosureReadiness(sealed,index,manifest),/false closure/);
 const falsified=structuredClone(doc);
 falsified.closure.main_integration_sha="3ee43044abdf0d16e126258c95b260c24bfe3bd7";
 assert.throws(()=>validateBranchClosureReadiness(falsified,index,manifest),/false closure/);
});
test("audit-hardening: reject omissions, forged blobs, priority drift, and mode-only vs content confusion",()=>{
 const missing=structuredClone(doc);
 missing.rows.pop();
 assert.throws(()=>validateBranchClosureReadiness(missing,index,manifest),/incorrect full delta/);
 const fake=structuredClone(doc);
 fake.rows[0][2]="0".repeat(40);
 assert.throws(()=>validateBranchClosureReadiness(fake,index,manifest),/forged historical evidence/);
 const classification=structuredClone(doc);
 classification.rows.find(x=>x[8]==="P0")[8]="P2";
 assert.throws(()=>validateBranchClosureReadiness(classification,index,manifest),/priority\/path classification drift/);
 const mode=structuredClone(doc);
 mode.rows.find(x=>x[10]==="MODE_ONLY_KEEP_CANONICAL_PENDING_PROOF")[10]="CONTENT_SEMANTIC_REVIEW_REQUIRED";
 assert.throws(()=>validateBranchClosureReadiness(mode,index,manifest),/mode-only drift mislabeled/);
});
