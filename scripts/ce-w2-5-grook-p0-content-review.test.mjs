import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const readJson = (p) => JSON.parse(readFileSync(new URL(p,root),"utf8"));
const readSource = (p) => readFileSync(new URL(p,root),"utf8");
const path = "registers/governance/ce-w2-5-grook-p0-content-review-20261120.v1.json";
test("W2.5.3: all 11 P0 reviewed, pinned and held without a false SEALED claim", () => {
 const r=readJson(path), q=readJson(r.review_input_path);
 assert.equal(r.protocol,"CE.CROSS.W2.5.3.GROOK_P0_CONTENT_REVIEW.v1");
 assert.equal(r.branch,q.origin_branch);
 assert.equal(r.source_commit_sha,q.origin_commit_sha);
 assert.equal(r.source_tree_sha,q.origin_tree_sha);
 assert.equal(r.main_review_sha,"f7a5c5c41ec51812708283032400b462a5b8a1db");
 assert.equal(r.metrics.p0_items,11);
 assert.equal(r.metrics.compared_content,11);
 assert.equal(r.metrics.proposed_preserve_main,11);
 assert.equal(r.records.length,q.queue.length);
 assert.equal(new Set(r.records.map(x=>x.path)).size,11);
 for(let i=0;i<q.queue.length;i++){
  const item=r.records[i],source=q.queue[i];
  assert.equal(item.path,source.path);
  assert.equal(item.source_blob_sha,source.source_blob_sha);
  assert.equal(item.baseline_main_blob_sha,source.baseline_blob_sha);
  assert.equal(item.content_review,"DONE_IMMUTABLE_BLOBS");
  assert.equal(item.recommendation,"PRESERVE_CANONICAL_NO_SOURCE_OVERWRITE");
  assert.ok(item.observed_content_delta.length>20);
  assert.ok(item.required_proof.length>20);
  assert.equal(item.final_semantic_decision,null);
  assert.equal(item.independent_review,"NOT_DONE");
  assert.equal(item.merge_eligible,false);
 }
 assert.equal(r.metrics.semantic_final_approved,0);
 assert.equal(r.metrics.independent_reviews_completed,0);
 assert.equal(r.metrics.branch_sealed,0);
 assert.equal(r.metrics.merges,0);
 assert.equal(r.publication_authorized,false);
 assert.equal(r.remote_database_write_authorized,false);
 assert.equal(r.source_branch_deletion_authorized,false);
 assert.equal(r.auth_secret_rotation_verified,false);
 assert.equal(r.security_release_gate,"HOLD");
});
