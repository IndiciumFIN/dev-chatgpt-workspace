import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {classifyPath} from "./ce-w2-5-orphan-risk-screen.mjs";
import {loadActionQueue} from "./ce-w2-5-action-queue.mjs";
import {normalizeReviewEvidence,projectEvidenceReuse} from "./ce-w2-5-p0-evidence-reuse.mjs";
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const index=read("registers/governance/ce-w2-4-orphan-full-file-index-20261120.v1.json");
const wave=read("registers/governance/ce-w2-5-p0-eighthwave-review-20261121.v1.json");
test("eighth W2.5 wave pins eleven P0 rows: 10 reuses and one new fail-open auth HOLD",()=>{
 loadActionQueue(100);
 const ptr=index.sources.find(x=>x.source_sha===wave.source_commit_sha);
 assert.ok(ptr);
 assert.ok(ptr.branches.includes(wave.source_branch));
 assert.equal(ptr.source_tree_sha,wave.source_tree_sha);
 assert.equal(ptr.manifest_path,wave.source_manifest_path);
 assert.equal(ptr.manifest_blob_sha,wave.source_manifest_blob_sha);
 assert.equal(index.batches.find(x=>x.path===ptr.manifest_path).git_blob_sha,wave.source_manifest_blob_sha);
 const src=read(ptr.manifest_path).sources.find(x=>x.source_sha===wave.source_commit_sha);
 assert.ok(src);
 assert.deepEqual(wave.inventoried_relations,{E:1312,C:1409,D:134,S:0,T:287});
 assert.equal(wave.nonidentical_source_files,421);
 assert.equal(wave.p0_occurrences,11);
 assert.equal(wave.records.length,11);
 const p0=src.rows.filter(r=>["D","S","T"].includes(r[1])&&classifyPath(r[0])[0]==="P0");
 assert.equal(p0.length,11);
 const earlier=new Map(wave.prior_review_paths.flatMap(p=>read(p).records).map(x=>[JSON.stringify([x.path,x.source_blob_sha]),x]));
 const unique=new Set();
 for(const rec of wave.records){
   const row=p0.find(r=>r[0]===rec.path&&r[2]===rec.source_blob_sha);
   assert.ok(row,"missing Git blob from source manifest "+rec.path);
   assert.equal(rec.relationship,row[1]);
   assert.equal(rec.historical_main_blob_sha,row[3]||null);
   if(row[4]!==undefined)assert.equal(rec.source_mode,row[4]);
   else assert.match(rec.source_mode,/^100(644|755)$/);
   const key=JSON.stringify([rec.path,rec.source_blob_sha]);
   assert.ok(!unique.has(key));unique.add(key);
   assert.equal(rec.exact_reuse_from_prior,earlier.has(key));
   if(earlier.has(key))assert.equal(rec.provisional_decision,earlier.get(key).provisional_decision);
   else {
     assert.equal(rec.path,"src/lib/auth/server.ts");
     assert.equal(rec.relationship,"D");
     assert.equal(rec.source_blob_sha,"b32a0af440b1012db7acf3d5ff937af0648a95bc");
     assert.equal(rec.comparison_main_blob_sha,"842ec9cd32dc07242ecfc29ea1d57db4d39ee8b1");
     assert.equal(rec.provisional_decision,"HOLD_LEGACY_AUTH_SERVER_FAIL_OPEN_UNSET_FLAG");
   }
   assert.equal(rec.status,"HOLD_INDEPENDENT_REVIEW");
   assert.equal(rec.final_semantic_disposition,false);
   assert.ok(rec.required_next_evidence.length>65);
 }
 assert.equal(wave.exact_reuses,10);
 assert.equal(wave.new_distinct_review_objects,1);
 assert.equal(wave.eighth_wave_prelim_unique_p0,33);
 assert.equal(wave.eighth_wave_prelim_pct,9.19);
 for(const f of ["active_auth_admission","independent_review_complete","branch_sealed","merge_authorized","remote_db_write","production_deploy_authorized","release_eligible"])assert.equal(wave[f],false);
});
test("eighth wave forbids historical fail-open auth admission, reject forged approvals",()=>{
 const newItems=wave.records.filter(x=>!x.exact_reuse_from_prior);
 assert.equal(newItems.length,1);
 assert.equal(newItems[0].path,"src/lib/auth/server.ts");
 assert.match(newItems[0].finding,/VITE_AUTH_ENABLED/);
 assert.match(newItems[0].finding,/canonical explicit opt-in/);
 const report=projectEvidenceReuse();
 assert.equal(report.reviewed_p0_unique_objects,33);
 assert.equal(report.projectable_p0_unique_objects,23);
 assert.equal(report.unprojected_baseline_hold_objects,10);
 assert.equal(report.source_only_review_objects_without_canonical_baseline,10);
 assert.equal(report.remaining_p0_unique_objects,326);
 assert.equal(report.direct_review_registrations,103);
 assert.equal(report.independent_approvals,0);
 assert.equal(report.branch_closures,0);
 assert.equal(report.remote_db_writes,0);
 const docs=[...wave.prior_review_paths.map(read),wave];
 const forged=structuredClone(docs);
 forged[7].records[0].status="APPROVED";
 assert.throws(()=>normalizeReviewEvidence(forged),/claims closure/);
 const spoof=structuredClone(docs);
 spoof[7].records[0].source_blob_sha="wrong";
 assert.throws(()=>normalizeReviewEvidence(spoof),/invalid source evidence/);
});
