#!/usr/bin/env node
/** Fail closed: deterministic MOF profile/evidence contract check, not a conformity certification. */
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
const root=resolve(import.meta.dirname,'../..');
const file=p=>JSON.parse(readFileSync(join(root,p),'utf8'));
const p=file('registers/canonical/mof-implementation-profile.v1.json');
const source=file('audit-evidence/mof-foundation-recovery/20261102/source-integrity/manifest.json');
const latest=file('audit-evidence/mof-foundation-recovery/20261102/sources/01_CKO_M3_META_METAMODEL_v1.0.0-rc3.schema.json');
const older=file('audit-evidence/mof-foundation-recovery/20261102/sources/CKO_M3_META_METAMODEL_v0.3.0.schema.json');
const queue=file('registers/pmo/queue.v1.json');
assert.equal(p.registryId,'CE-MOF-IMPLEMENTATION-PROFILE-V1');
assert.equal(p.canonicalStatus,'PRE_CANONICAL');
assert.equal(p.releaseGate,'HOLD_HUMAN');
assert.equal(p.chosenApproach.mofConformanceClaim,'NONE');
assert.equal(p.chosenApproach.primaryProfile,'EMOF_INSPIRED_PROJECT_M3');
assert.equal(p.chosenApproach.noDuplicateGovernanceTables,true);
assert.equal(p.chosenApproach.secondaryProfile,'CMOF_SELECTIVE_WHEN_VERIFIED');
assert.equal(p.chosenApproach.eclipseEMF.status,'OPTIONAL_INTEROPERABILITY_ADAPTER_NOT_CORE_RUNTIME');
assert.equal(p.chosenApproach.projectMetalevelConvention.length,4);
assert.deepEqual(p.chosenApproach.projectMetalevelConvention.map(x=>x.level),['M3','M2','M1','M0']);
assert.deepEqual(p.chosenApproach.environmentProgression,['PLANNING','TEST','PRODUCTION']);
assert.equal(p.officialNormativeSources.length,2);
const current=p.officialNormativeSources.find(x=>x.identifier==='OMG-MOF-2.5.1');
const old=p.officialNormativeSources.find(x=>x.identifier==='OMG-MOF-2.0');
assert.equal(current.role,'PRIMARY_FORMAL_BASELINE');
assert.equal(old.role,'HISTORICAL_PRIMARY_REFERENCE_FROM_USER_UPLOAD');
assert.equal(old.sha256.length,64);
assert.equal(old.gitBinaryStored,false);
assert.equal(source.verified_count,4);
assert.equal(source.status,'OFFICIAL_BINARY_FETCH_VERIFIED');
assert.equal(source.original_binary_content_committed,false);
assert.equal(source.sources.find(x=>x.source_id==='OMG-MOF-2.5.1')?.sha256,current.sha256);
assert.equal(latest.$id,'urn:cko:m3:meta-metamodel:1.0.0-rc3');
assert.equal(older.$id,'urn:cko:m3:meta-metamodel:0.3.0');
assert.ok(latest.required.includes('invariants'));
assert.ok(latest.required.includes('binding_definitions'));
assert.ok(p.referenceFromUserPDF.some(x=>x.section==='7.2'&&x.pdfPage===20));
assert.ok(p.requiredIndependentEvidence.length>=10);
assert.ok(p.knownFindings.length>=4&&p.knownFindings.every(x=>x.status==='OPEN'));
assert.ok(queue.items.some(x=>x.id===p.workOrder&&x.status!=='DONE'));
assert.ok(existsSync(join(root,'scripts/ce-agents/audit-mof-foundation.mjs')));
console.log(JSON.stringify({status:'MOF_ARCHITECTURAL_PROFILE_EVIDENCE_VALID',source:'user-uploaded-MOF-2.0+official-MOF-2.5.1',profile:'EMOF-inspired',omgConformance:'NOT_CLAIMED',issues:p.knownFindings.length,release:'HOLD_HUMAN'}));
