import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validateCommanderReadModel as check} from '../src/lib/commander/read-model.ts';
const q=JSON.parse(readFileSync('registers/pmo/queue.v1.json','utf8'));
const l=JSON.parse(readFileSync('registers/commander/lanes.v1.json','utf8'));
const run=(edit)=>{const a=structuredClone(q),b=structuredClone(l);edit(a,b);return check(a,b).join('|')};
test('baseline canonical register valid',()=>assert.deepEqual(check(q,l),[]));
test('refuse mutable authority',()=>assert.match(run(a=>{a.readOnly=false}),/PMO_NOT_READ_ONLY/));
test('refuse second PMO',()=>assert.match(run(a=>{a.canonicalSource='other'}),/PMO_WRONG_AUTHORITY/));
test('refuse duplicate WO',()=>assert.match(run(a=>{a.items[1].id=a.items[0].id}),/DUPLICATE_WO/));
test('refuse DONE without evidence',()=>assert.match(run(a=>{a.items.find(x=>x.status==='DONE').evidence=[]}),/DONE_NO_EVIDENCE/));
test('refuse unknown dependencies',()=>assert.match(run(a=>{a.items[0].dependencies.push('WO-UNKNOWN')}),/BAD_DEPENDENCY/));
test('refuse dependency cycle',()=>assert.match(run(a=>{a.items[0].dependencies=['WO-PMO-001'];a.items[1].dependencies=['WO-ADM-001']}),/DEPENDENCY_CYCLE/));
test('refuse event drift',()=>assert.match(run(a=>{a.items[0].status='PAUSED'}),/EVENT_STATUS_MISMATCH/));
test('refuse fake agent dispatch',()=>assert.match(run((a,b)=>{b.lanes[0].dispatched=true}),/LANE_NOT_CANDIDATE/));
test('refuse remote write policy',()=>assert.match(run((a,b)=>{b.governance.remoteWritesAllowed=true}),/UNAUTHORIZED_DISPATCH/));
test('refuse wrong source SHA',()=>assert.match(run((a,b)=>{b.lanes[0].sourceCommit='000'}),/INVALID_SOURCE_SHA/));
test('refuse missing agent WO',()=>assert.match(run((a,b)=>{b.lanes[0].workOrderId='WO-MISSING'}),/UNKNOWN_LANE_WO/));
