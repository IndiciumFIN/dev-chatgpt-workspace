export type CanonicalLocale = typeof localeRegistry[number]["id"];
export const localeIds = localeRegistry.map(item => item.id);
export const defaultLocale: CanonicalLocale = "pt-BR";
export function isCanonicalLocale(value: unknown): value is CanonicalLocale {
  return typeof value === "string" && localeIds.some(code => code === value);
}
/** Existing SEO configuration, NOT proof of translation approval. */
export const legacySeoLocales = localeRegistry.filter(item => item.seoEligibility === "legacy_declared_requires_review").map(item => item.id);
/**
 * Idiomas que tem DICIONARIO DE INTERFACE proprio.
 *
 * `partial_existing` marca os quatro idiomas que o site realmente entrega.
 * Ter vocabulario de acessibilidade em outros idiomas nao prova que a
 * interface completa ou o conteudo estejam traduzidos.
 *
 * Importante: "interface dictionary" nao e "conteudo traduzido". O
 * `content` de todos os 19 continua `not_verified` — o texto clinico e
 * pt-BR por decisao. O que esta aqui e o que o chrome consegue exibir.
 */
export const localesWithInterface: CanonicalLocale[] = localeRegistry
  .filter(item => item.interfaceDictionary !== "missing")
  .map(item => item.id);
export function hasInterfaceDictionary(value: unknown): boolean {
  return isCanonicalLocale(value) && localesWithInterface.includes(value);
}
/**
 * O idioma em que a PAGINA ESTA DE FATO.
 *
 * Nao e o idioma escolhido e nao oidioma traduzido: e o idioma do texto que o
 * visitante esta lendo. Para os 15 idiomas sem dicionario de interface, o
 * chrome cai no fallback de `src/lib/chrome.tsx` e a pagina inteira e
 * portuguesa. Declarar `lang="ja"` nesse caso faz o leitor de tela ler
 * portugues com fonetica japonesa — WCAG 3.1.1 (Idioma da Pagina).
 *
 * Importante: `dir` NAO vem daqui. O eixo `rtl` em arabe e um recurso visual
 * proposital, independente do texto exibido, e nao e responsabilidade desta
 * funcao.
 */
export function contentLocale(value: unknown): string {
  if (typeof value !== "string") return defaultLocale;
  return hasInterfaceDictionary(value) ? value : defaultLocale;
}
