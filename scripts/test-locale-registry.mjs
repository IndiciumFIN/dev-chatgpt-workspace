import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const base = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, base),'utf8');
const reg=JSON.parse(read('registers/i18n/locale-register.v1.json'));
const ids=reg.locales.map(x=>x.id);
assert.equal(ids.length,19);assert.equal(new Set(ids).size,19);
assert.equal(reg.locales.filter(x=>x.direction==='rtl').map(x=>x.id).join(','),'ar');
assert.equal(reg.locales.filter(x=>x.interfaceDictionary==='partial_existing').map(x=>x.id).join(','),'pt-BR,en,es,fr');
assert.equal(reg.locales.filter(x=>x.interfaceDictionary==='interface_ready').length,15);
assert.equal(reg.locales.filter(x=>x.interfaceDictionary==='missing').length,0);
assert.ok(reg.locales.every(x=>x.content==='not_verified'));
const header=read('src/lib/header-i18n.ts');
const translate=read('src/lib/translate.ts');
const seo=read('src/lib/seo.ts');
assert.match(header,/headerLocales = localeRegistry/);
assert.match(translate,/isCanonicalLocale\(value\)/);
assert.match(seo,/const locales = legacySeoLocales/);
assert.doesNotMatch(seo,/\["pt-BR", "en", "es", "fr"\]/);
assert.match(seo,/isCanonicalLocale\(value\)/);
console.log('PASS: 19 canonical locales, 19 interface dictionaries, SEO still blocked, shared imports');
